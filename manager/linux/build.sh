#!/usr/bin/env bash
# Builds CrabMods Manager for Linux: build/linux/CrabModsManager, its tests, and CrabModsManager-x86_64.AppImage.
# Needs g++ (C++20), libsdl2-dev and libcurl4-openssl-dev; the AppImage step downloads linuxdeploy.
# Usage: manager/linux/build.sh [test] [appimage]
#   test      run the manager's tests and --selftest (no display needed)
#   appimage  build/linux/CrabModsManager-x86_64.AppImage and its .sha256
set -euo pipefail
cd "$(dirname "$0")/../.."

CXX="${CXX:-g++}"
OUT=build/linux
mkdir -p "$OUT/obj"
IMGUI=third_party/imgui
CXXFLAGS=(-std=c++20 -O2 -Wall -Wextra -Wno-unused-parameter -Wno-missing-field-initializers)
SDL_CFLAGS=$(sdl2-config --cflags)
SDL_LIBS=$(sdl2-config --libs)

# The font, compiled in (the same header build.sh writes for Windows).
FONT=manager/fonts/Roboto-Medium.ttf
if [ ! "$OUT/obj/font_data.hpp" -nt "$FONT" ]; then
    {
        echo "// Generated by manager/linux/build.sh from $FONT"
        echo "#pragma once"
        echo "static const unsigned char kFontData[] = {"
        od -An -v -tx1 "$FONT" | sed 's/ *\([0-9a-f][0-9a-f]\)/0x\1,/g'
        echo "};"
    } >"$OUT/obj/font_data.hpp"
fi

IMGUI_CORE=()
for f in "$IMGUI"/imgui.cpp "$IMGUI"/imgui_draw.cpp "$IMGUI"/imgui_tables.cpp "$IMGUI"/imgui_widgets.cpp; do
    o="$OUT/obj/imgui_$(basename "${f%.cpp}").o"
    [ "$o" -nt "$f" ] || "$CXX" -std=c++20 -O2 -I"$IMGUI" -c "$f" -o "$o"
    IMGUI_CORE+=("$o")
done
IMGUI_BACKENDS=()
for f in "$IMGUI"/backends/imgui_impl_sdl2.cpp "$IMGUI"/backends/imgui_impl_opengl3.cpp; do
    o="$OUT/obj/imgui_$(basename "${f%.cpp}").o"
    # shellcheck disable=SC2086
    [ "$o" -nt "$f" ] || "$CXX" -std=c++20 -O2 -I"$IMGUI" $SDL_CFLAGS -c "$f" -o "$o"
    IMGUI_BACKENDS+=("$o")
done

# app.cpp is shared with Windows; platform_linux.cpp and linux_main.cpp are the Linux side.
# shellcheck disable=SC2086
"$CXX" "${CXXFLAGS[@]}" -I"$IMGUI" -I"$OUT/obj" $SDL_CFLAGS manager/app.cpp manager/platform_linux.cpp manager/linux_main.cpp \
    "${IMGUI_CORE[@]}" "${IMGUI_BACKENDS[@]}" $SDL_LIBS -lcurl -lGL -ldl -pthread -o "$OUT/CrabModsManager"
"$CXX" "${CXXFLAGS[@]}" tests/manager_core_test.cpp -o "$OUT/manager_core_test"
"$CXX" "${CXXFLAGS[@]}" -I"$IMGUI" -I"$OUT/obj" tests/manager_app_test.cpp manager/app.cpp "${IMGUI_CORE[@]}" -pthread \
    -o "$OUT/manager_app_test"
# shellcheck disable=SC2086
"$CXX" "${CXXFLAGS[@]}" $SDL_CFLAGS tests/platform_linux_test.cpp manager/platform_linux.cpp $SDL_LIBS -lcurl -pthread \
    -o "$OUT/platform_linux_test"
echo "built: $OUT/CrabModsManager (+ tests)"

for arg in "$@"; do
    case "$arg" in
    test)
        # The core tests read the catalogs and DLLs from build/ when they are there (a Windows build); without them
        # those cases are skipped.
        "$OUT/manager_core_test" build
        "$OUT/manager_app_test"
        "$OUT/manager_app_test" migrate
        "$OUT/platform_linux_test"
        # The real thing against GitHub (the releases, their checksums and catalogs), in throwaway folders.
        tmp=$(mktemp -d)
        rc=0
        XDG_CONFIG_HOME="$tmp/config" XDG_CACHE_HOME="$tmp/cache" "$OUT/CrabModsManager" --selftest --report || rc=$?
        rm -rf "$tmp"
        [ "$rc" = 0 ] || exit "$rc"
        ;;
    appimage)
        TOOLS="$OUT/tools"
        mkdir -p "$TOOLS"
        LD="$TOOLS/linuxdeploy-x86_64.AppImage"
        if [ ! -x "$LD" ]; then
            curl -fsSL -o "$LD" https://github.com/linuxdeploy/linuxdeploy/releases/download/continuous/linuxdeploy-x86_64.AppImage
            chmod +x "$LD"
        fi
        APPDIR="$OUT/AppDir"
        rm -rf "$APPDIR"
        mkdir -p "$APPDIR/usr/bin"
        cp "$OUT/CrabModsManager" "$APPDIR/usr/bin/"
        strip "$APPDIR/usr/bin/CrabModsManager"
        # Bundles SDL2 and libcurl with what they need; the graphics driver and glibc come from the system.
        (cd "$OUT" && APPIMAGE_EXTRACT_AND_RUN=1 ARCH=x86_64 LDAI_OUTPUT=CrabModsManager-x86_64.AppImage \
            "$PWD/tools/linuxdeploy-x86_64.AppImage" --appdir AppDir \
            --desktop-file "$OLDPWD/manager/linux/CrabModsManager.desktop" \
            --icon-file "$OLDPWD/manager/linux/CrabModsManager.png" \
            --output appimage)
        (cd "$OUT" && sha256sum CrabModsManager-x86_64.AppImage >CrabModsManager-x86_64.AppImage.sha256)
        echo "packaged: $OUT/CrabModsManager-x86_64.AppImage"
        ;;
    esac
done
