"""Emit readable C++ SDK headers from sdk.json (output of ue_reflect.py)."""
import json
import os
import sys

src = sys.argv[1] if len(sys.argv) > 1 else "sdk.json"
outdir = sys.argv[2] if len(sys.argv) > 2 else "sdk"
d = json.load(open(src))
os.makedirs(outdir, exist_ok=True)

GAME_PKG = "/Script/CrabChampions"
game_classes = [c for c in d["classes"] if c["pkg"] == GAME_PKG]
# Structs/enums carry no package; treat Crab-prefixed ones as game types.
game_structs = [s for s in d["structs"] if s["name"].startswith("FCrab")]
game_enums = [e for e in d["enums"] if e["name"].startswith("ECrab")]


def prop_line(p, size_hint=None):
    off = p.get("offset")
    flags = " ".join(f for f in p["flags"] if f in ("Net", "RepNotify", "SaveGame", "Transient", "Config", "Edit",
                                                     "BlueprintVisible", "OutParm", "ReturnParm", "ConstParm"))
    extra = []
    if p.get("repnotify"):
        extra.append(f"OnRep={p['repnotify']}")
    if "bitmask" in p:
        extra.append(f"mask=0x{p['bitmask']:02X}")
    dim = f"[{p['dim']}]" if p.get("dim") else ""
    offs = f"0x{off:04X}" if isinstance(off, int) else "  ?   "
    return f"    {p['type']} {p['name']}{dim};".ljust(64) + f" // {offs} {flags} {' '.join(extra)}".rstrip()


def func_lines(f):
    params = [p for p in f["params"] if "ReturnParm" not in p["flags"]]
    ret = next((p["type"] for p in f["params"] if "ReturnParm" in p["flags"]), "void")
    args = ", ".join(f"{p['type']}{'&' if 'OutParm' in p['flags'] else ''} {p['name']}" for p in params)
    fl = " ".join(x for x in f["flags"] if x in ("Net", "NetReliable", "NetServer", "NetClient", "NetMulticast",
                                                  "Exec", "BlueprintEvent", "BlueprintCallable", "Static", "Native"))
    return [f"    {ret} {f['name']}({args});".ljust(64) + f" // {fl} parms=0x{f['parmsize']:X}"]


def emit_class(c):
    out = [f"// {c['pkg']}  params@{c['params_va']}  StaticClass@{c['staticclass_va']}",
           f"// Size: 0x{(c['size'] or 0):04X}  Config: {c['config']}",
           f"class {c['name']} : public {c['super'] or 'UObject'}", "{", "public:"]
    out += [prop_line(p) for p in c["props"]]
    if c["functions"]:
        out.append("")
        for f in c["functions"]:
            out += func_lines(f)
    out += ["};", ""]
    return out


def emit_struct(s):
    out = [f"// Size: 0x{s['size']:04X} Align: {s['align']}",
           f"struct {s['name']}" + (f" : public {s['super']}" if s.get("super") else ""), "{"]
    out += [prop_line(p) for p in s["props"]]
    out += ["};", ""]
    return out


def emit_enum(e):
    out = [f"enum class {e['name']}", "{"]
    out += [f"    {n.split('::')[-1]} = {v}," for n, v in e["values"]]
    out += ["};", ""]
    return out


def write(name, blocks):
    with open(os.path.join(outdir, name), "w") as fh:
        fh.write("// Generated by emit_sdk.py from static UHT reflection tables (UE 4.27).\n#pragma once\n\n")
        for b in blocks:
            fh.write("\n".join(b) + "\n")


write("CrabChampions_enums.hpp", [emit_enum(e) for e in game_enums])
write("CrabChampions_structs.hpp", [emit_struct(s) for s in game_structs])
write("CrabChampions_classes.hpp", [emit_class(c) for c in game_classes])
by_pkg = {}
for c in d["classes"]:
    if c["pkg"] != GAME_PKG:
        by_pkg.setdefault((c["pkg"] or "/Script/Unknown").split("/")[-1], []).append(c)
for pkg, cs in by_pkg.items():
    write(f"Engine_{pkg}_classes.hpp", [emit_class(c) for c in cs])
write("Engine_structs.hpp", [emit_struct(s) for s in d["structs"] if not s["name"].startswith("FCrab")])
write("Engine_enums.hpp", [emit_enum(e) for e in d["enums"] if not e["name"].startswith("ECrab")])
print(f"game: {len(game_classes)} classes, {len(game_structs)} structs, {len(game_enums)} enums; engine pkgs: {len(by_pkg)}")
